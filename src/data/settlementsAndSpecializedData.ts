// Data store for Eco-Villages/Settlement Development, Specialized Therapeutic Programs,
// and Outdoor/Scientific Expeditions in partnership with institutes of Uzbekistan, Belarus, and Israel.

export interface LotType {
  type: string;
  areaSqM: number;
  bedrooms: number;
  priceUsd: number;
  yieldUsdMonth: number;
  description: string;
  features: string[];
}

export interface MasterPlanPhase {
  phase: string;
  title: string;
  timeline: string;
  status: 'completed' | 'in_progress' | 'upcoming';
  description: string;
}

export interface SettlementProject {
  id: string;
  name: string;
  category: 'village' | 'dacha_estate' | 'hotel' | 'sanatorium';
  categoryLabel: string;
  location: string;
  altitudeMeters: number;
  status: 'active_construction' | 'planning' | 'sales_open' | 'operating';
  statusLabel: string;
  totalAreaHectares: number;
  unitsTotal: number;
  unitsAvailable: number;
  priceFromUsd: number;
  roiAnnualPercent: string;
  architecturalStyle: string;
  ecoStandards: string[];
  biohackingInfrastructure: string[];
  lotTypes: LotType[];
  masterPlanPhases: MasterPlanPhase[];
  description: string;
  investmentModel: string;
  amenities: { name: string; icon: string }[];
}

export interface ProgramPhase {
  phaseNumber: number;
  title: string;
  duration: string;
  subtitle: string;
  focus: string;
  activities: string[];
  setting: string;
  dimensionTags: ('body' | 'mind' | 'soul' | 'psyche')[];
}

export interface SpecializedProgram {
  id: string;
  category: 'family_separation_reunion' | 'neurodivergent_children' | 'addiction_codependency' | 'corporate_campaign';
  categoryLabel: string;
  title: string;
  subtitle: string;
  badge: string;
  duration: string;
  phases: ProgramPhase[];
  targetAudience: string;
  methodology: string;
  partnerInstitutes: { name: string; country: string; role: string }[];
  priceUsd: number;
  grantCoveragePercent: number;
  dates: string;
  supervisionFollowUp: string;
  hosts: { name: string; role: string; credentials: string }[];
  keyOutcomes: string[];
}

export interface OutdoorExpedition {
  id: string;
  type: 'horse_riding' | 'water_sports' | 'mountain_hiking' | 'science_expedition' | 'astronomy_night';
  typeLabel: string;
  title: string;
  subtitle: string;
  duration: string;
  difficulty: 'easy' | 'moderate' | 'advanced';
  difficultyLabel: string;
  location: string;
  altitudeMeters?: number;
  scientificPartners: { name: string; country: 'Узбекистан' | 'Беларусь' | 'Израиль'; role: string }[];
  keyActivities: string[];
  equipmentProvided: string[];
  priceUsd: number;
  maxGroupSize: number;
  description: string;
  researchProtocol: string;
  badge: string;
  nextDates: string[];
}

